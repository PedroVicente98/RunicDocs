"""Write content/Update timeline.md: every change to the notes, newest first, from the git history.

Usage:
    python3 tools/build_changelog.py                     # from the commits on the current branch
    python3 tools/build_changelog.py --staged "Subject"  # also puts the staged changes on top, as the commit about to be made

The deploy workflow runs it before building the site (with the full history), so the site is always current.
Run it with --staged before committing note changes to keep the copy in the vault current too.
"""
import argparse
import datetime as dt
import subprocess
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
NOTE = CONTENT / "Update timeline.md"
REPO_URL = "https://github.com/PedroVicente98/RunicDocs"
LIST_LIMIT = 40           # above this many notes in one group, show counts per folder instead
GENERATED = ("Development/",)  # regenerated notes are summarized, not listed
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December"]


def git(*args: str) -> str:
    return subprocess.run(["git", "-c", "core.quotePath=false", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def parse_status(lines):
    """name-status lines → list of (kind, path) for notes under content/."""
    out = []
    for line in lines:
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        code = parts[0][0]
        path = parts[-1]
        if not (path.startswith("content/") and path.endswith(".md")):
            continue
        rel = path[len("content/"):]
        if rel == NOTE.name:
            continue
        kind = {"A": "added", "D": "removed", "R": "renamed"}.get(code, "changed")
        out.append((kind, rel))
    return out


def commits():
    raw = git("log", "--no-merges", "-M", "--name-status", "--date=short",
              "--format=%x1e%H%x1f%ad%x1f%s", "--", "content")
    for block in raw.split("\x1e"):
        block = block.strip("\n")
        if not block:
            continue
        head, *rest = block.split("\n")
        sha, date, subject = head.split("\x1f")
        files = parse_status([l for l in rest if l.strip()])
        if files:
            yield {"sha": sha, "date": date, "subject": subject, "files": files}


def staged(subject: str):
    files = parse_status(git("diff", "--cached", "-M", "--name-status", "--", "content").splitlines())
    if files:
        return {"sha": None, "date": dt.date.today().isoformat(), "subject": subject, "files": files}
    return None


def link(rel: str) -> str:
    name = rel.rsplit("/", 1)[-1][:-3]
    if (CONTENT / rel).exists():
        return f"[[{name}]]"
    return name


def describe(kind: str, rels: list[str]) -> str:
    label = {"added": "Added", "changed": "Changed", "renamed": "Renamed to", "removed": "Removed"}[kind]
    plain = [r for r in rels if not r.startswith(GENERATED)]
    generated = [r for r in rels if r.startswith(GENERATED)]
    parts = []
    if len(plain) > LIST_LIMIT:
        per_folder = Counter(r.split("/", 1)[0] if "/" in r else "home" for r in plain)
        parts.append(f"{len(plain)} notes (" + ", ".join(f"{f} {n}" for f, n in sorted(per_folder.items())) + ")")
    elif plain:
        parts.append(", ".join(link(r) for r in sorted(plain)))
    if generated:
        parts.append(f"{len(generated)} generated Development notes")
    return f"{label}: " + "; ".join(parts)


def human_date(iso: str) -> str:
    d = dt.date.fromisoformat(iso)
    return f"{d.day} {MONTHS[d.month - 1]} {d.year}"


def render(entries) -> str:
    by_date: "OrderedDict[str, list]" = OrderedDict()
    for e in entries:
        by_date.setdefault(e["date"], []).append(e)
    newest = entries[0]["date"] if entries else dt.date.today().isoformat()
    lines = [
        "---",
        'title: "Update timeline"',
        "aliases:",
        '  - "Changelog"',
        "tags:",
        '  - "updates"',
        'created: "2026-11-16"',
        f'modified: "{newest}"',
        "---",
        "",
        "Every change to the notes, newest first: what each update was and which notes it touched. Generated by "
        "`tools/build_changelog.py` from the git history, so don't edit it by hand; the site rebuilds it on every deploy.",
        "",
    ]
    for date, items in by_date.items():
        lines.append(f"### {human_date(date)}")
        lines.append("")
        for e in items:
            ref = f" · [{e['sha'][:7]}]({REPO_URL}/commit/{e['sha']})" if e["sha"] else ""
            lines.append(f"- **{e['subject']}**{ref}")
            groups: "OrderedDict[str, list]" = OrderedDict((k, []) for k in ("added", "changed", "renamed", "removed"))
            for kind, rel in e["files"]:
                groups[kind].append(rel)
            for kind, rels in groups.items():
                if rels:
                    lines.append(f"    - {describe(kind, rels)}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--staged", metavar="SUBJECT", help="put the staged changes on top, under this subject")
    args = ap.parse_args()
    entries = list(commits())
    if args.staged:
        top = staged(args.staged)
        if top:
            entries.insert(0, top)
    NOTE.write_text(render(entries))
    print(f"Wrote {NOTE.relative_to(ROOT)}: {len(entries)} updates")


if __name__ == "__main__":
    main()
